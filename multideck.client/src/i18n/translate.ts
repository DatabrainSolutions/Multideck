function preserveCase(source: string, translated: string, language: LanguageCode) {
  if (language === "ar") return translated
  if (source.toUpperCase() === source && source.length > 1) return translated.toUpperCase()
  if (source[0]?.toUpperCase() === source[0]) return `${translated[0]?.toUpperCase() ?? ""}${translated.slice(1)}`
  return translated
}

function translateToken(token: string, language: LanguageCode) {
  if (language === "en-GB") return token
  if (language === "en-US") return britishToAmerican[token] ?? token

  const dictionary = wordDictionaries[language]
  const translated = dictionary[token.toLowerCase()]
  return translated ? preserveCase(token, translated, language) : token
}

export function translateText(text: string, language: LanguageCode) {
  if (language === "en-GB" || text.trim().length === 0) return text

  if (language === "en-US") {
    return Object.entries(britishToAmerican).reduce(
      (current, [source, replacement]) => current.replaceAll(source, replacement),
      text,
    )
  }

  const [, leading = "", body = "", trailing = ""] = text.match(/^(\s*)(.*?)(\s*)$/s) ?? []
  const phrase = phrases[body]?.[language]
  if (phrase) return `${leading}${phrase}${trailing}`

  const translatedBody = body.replace(/\p{L}[\p{L}'’&-]*/gu, (token) => translateToken(token, language))
  return `${leading}${translatedBody}${trailing}`
}
