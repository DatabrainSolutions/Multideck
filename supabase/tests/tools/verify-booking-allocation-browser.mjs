import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
const [url, packagePath, screenshotPath] = process.argv.slice(2)
if (!/^http:\/\/127\.0\.0\.1:\d+\/$/.test(url ?? '') || !packagePath || !screenshotPath) throw Error('Usage: verifier <isolated local QA URL> <Playwright package path> <screenshot path>')
const { chromium } = createRequire(import.meta.url)(packagePath)
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' })
  page.setDefaultTimeout(10000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  for (const language of ['en-GB', 'en-US']) {
    await page.goto(`${url}?language=${language}`)
    await page.getByRole('heading', { name: 'Cargo allocation QA' }).waitFor()
    assert.equal(await page.locator('fieldset').count(), 2)
    assert.equal(await page.locator('.vite-error-overlay').count(), 0)
    console.log(`${language}: page loaded, real allocation editor rendered`)
    const first = page.locator('fieldset').first(), second = page.locator('fieldset').nth(1)
    await second.getByRole('button', { name: 'Use remaining quantities' }).click()
    assert.equal(await second.getByRole('textbox', { name: 'Packages / pieces', exact: true }).inputValue(), '4')
    assert.equal(await second.getByRole('textbox', { name: 'Gross weight (kg)', exact: true }).inputValue(), '400.25')
    assert.equal(await second.getByRole('textbox', { name: 'Volume (CBM)', exact: true }).inputValue(), '6.125')
    await second.getByRole('textbox', { name: 'Packages / pieces', exact: true }).fill('5')
    await page.getByRole('button', { name: 'Check allocations' }).click()
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-invalid') === 'true')
    assert.match(await page.locator('[aria-invalid=true]').first().getAttribute('aria-describedby'), /error/)
    await second.getByRole('textbox', { name: 'Packages / pieces', exact: true }).fill('4')
    await page.getByRole('button', { name: 'Add allocation', exact: true }).click()
    const third = page.locator('fieldset').nth(2)
    await page.waitForFunction(() => document.activeElement?.id.endsWith('-cargoId'))
    await third.getByRole('button', { name: 'Remove allocation 3' }).click()
    await page.waitForFunction(() => document.activeElement?.textContent === 'Keep allocation')
    await page.keyboard.press('Escape')
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Remove allocation 3')
    assert.equal(await page.locator('fieldset').count(), 3)
    await third.getByRole('button', { name: 'Remove allocation 3' }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Remove allocation', exact: true }).click()
    await page.waitForFunction(() => document.activeElement?.textContent === 'Add allocation')
    assert.equal(await page.locator('fieldset').count(), 2)
    await first.getByRole('combobox', { name: 'Routing scope' }).focus()
    await page.keyboard.press('Space')
    await page.getByRole('option', { name: /Leg 1/ }).click()
    await page.getByRole('button', { name: 'Check allocations' }).click()
    await page.waitForFunction(() => document.activeElement?.id.endsWith('-routeId'))
    assert.ok((await page.getByText('Use either whole-journey or individual-leg allocations for this cargo line, not both.').count()) > 0)
    await first.getByRole('combobox', { name: 'Routing scope' }).click()
    await page.getByRole('option', { name: 'Whole journey', exact: true }).click()
    await first.locator('summary').focus();await page.keyboard.press('Enter')
    await first.getByRole('textbox', { name: 'Allocation notes 1' }).fill('Packing list reviewed — keep customer wording.')
    for (const width of [320, 768, 1280]) {
      await page.setViewportSize({ width, height: 900 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width, `overflow at ${width}`)
    }
    await page.evaluate(() => { document.body.style.zoom = '2' })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 1280)
    await page.evaluate(() => { document.body.style.zoom = '1' })
    await page.getByRole('button', { name: 'Preview read-only' }).click()
    assert.equal(await page.locator('fieldset input, fieldset button, fieldset textarea').count(), 0)
    assert.equal(await first.getByText('Packing list reviewed — keep customer wording.', { exact: true }).count(), 1)
    await page.getByRole('button', { name: 'Return to editing' }).click()
    assert.equal(await first.getByRole('textbox', { name: 'Allocation notes 1' }).inputValue(), 'Packing list reviewed — keep customer wording.')
    console.log(`${language}: exact fills, validation focus, add/remove/cancel, routing scope, notes, read-only and responsive checks passed`)
  }
  assert.deepEqual(errors, [])
  await page.screenshot({ path: screenshotPath, fullPage: true })
  console.log(`No browser errors. Screenshot: ${screenshotPath}`)
} finally { await browser.close() }
