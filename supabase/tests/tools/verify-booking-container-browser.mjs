// Run against booking-container-operations-browser.mjs. Uses the desktop
// runtime's Playwright package, supplied explicitly; never installs a dependency.
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
const [url, packagePath, screenshotPath]=process.argv.slice(2)
if(!url || !packagePath || !screenshotPath)throw Error('Usage: verifier <isolated QA URL> <Playwright package path> <screenshot path>')
if(!/^http:\/\/127\.0\.0\.1:\d+\/$/.test(url))throw Error('Only the isolated local fixture is supported')
const {chromium}=createRequire(import.meta.url)(packagePath)
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true})
try {
  const page=await browser.newPage({viewport:{width:320,height:900},reducedMotion:'reduce'})
  page.setDefaultTimeout(10000)
  const errors=[];page.on('pageerror',error=>errors.push(error.message));page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
  for(const language of ['en-GB','en-US']) {
    await page.goto(`${url}?language=${language}`)
    const first=page.locator('fieldset').first()
    const summary=first.locator('summary')
    await summary.focus();await page.keyboard.press('Enter')
    await first.getByRole('textbox',{name:'Verified gross mass (kg)',exact:true}).fill('123456789012.123456')
    await first.getByRole('combobox',{name:'VGM method',exact:true}).click()
    await page.waitForFunction(()=>document.activeElement?.getAttribute('role')==='option')
    await page.keyboard.press('ArrowDown')
    await page.waitForFunction(()=>document.activeElement?.textContent?.includes('1 - Weighed packed container'))
    await page.keyboard.press('Enter')
    await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='VGM method')
    assert.equal(await page.evaluate(()=>document.activeElement.getAttribute('aria-label')),'VGM method')
    await first.getByRole('textbox',{name:'Tare weight (kg)',exact:true}).fill('1,00')
    await page.keyboard.press('Tab')
    await page.getByRole('button',{name:'View read-only',exact:true}).click()
    await page.getByRole('button',{name:'Edit draft',exact:true}).waitFor()
    assert.equal(await page.locator('fieldset input:not(:disabled)').count(),0)
    assert.equal(await first.getByText('1,00',{exact:true}).count(),1)
    await page.getByRole('button',{name:'Use Rail',exact:true}).click()
    await page.getByRole('button',{name:'Use Sea',exact:true}).waitFor()
    assert.ok((await first.innerText()).includes('VGM method'))
    const second=page.locator('fieldset').nth(1)
    await second.locator('summary').click()
    assert.ok(!(await second.innerText()).includes('VGM method'))
    const state=await page.locator('#receipt').textContent()
    const saved=JSON.parse(state)
    assert.equal(saved.containers[0].verifiedGrossMassKg,'123456789012.123456')
    assert.equal(saved.containers[0].tareWeightKg,'1,00')
    assert.equal(saved.containers[0].vgmMethod,'1')
    assert.deepEqual(saved.containers[1],{id:'two',number:'SYNTHETIC-2',type:'20GP',data:{}})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),320)
    await page.getByRole('button',{name:'Edit draft',exact:true}).click()
    await first.getByRole('combobox',{name:'VGM method',exact:true}).click()
    await page.getByRole('option',{name:'Not recorded',exact:true}).click()
    // VGM stays visible because its saved number is still present.
    await first.getByRole('combobox',{name:'Temperature unit',exact:true}).click()
    await page.getByRole('option',{name:'Not recorded',exact:true}).click()
    const cleared=JSON.parse(await page.locator('#receipt').textContent()).containers[0]
    assert.equal(cleared.vgmMethod,'');assert.equal(cleared.reeferUnit,'')
    await page.setViewportSize({width:1280,height:900})
    await page.evaluate(()=>{document.body.style.zoom='2'})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),1280)
    await page.evaluate(()=>{document.body.style.zoom='1'})
    await page.setViewportSize({width:320,height:900})
    console.log(`${language}: edit/read-only, keyboard, retained mode evidence, explicit clears, exact values and responsive checks passed`)
  }
  assert.deepEqual(errors,[])
  await page.screenshot({path:screenshotPath,fullPage:true})
  console.log(`No browser errors. Screenshot: ${screenshotPath}`)
} finally {await browser.close()}
