import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
const [url,packagePath,screenshot]=process.argv.slice(2)
if(!/^http:\/\/127\.0\.0\.1:\d+\/$/.test(url)||!packagePath||!screenshot)throw Error('Pass isolated fixture URL, Playwright package directory and screenshot path')
const {chromium}=createRequire(import.meta.url)(packagePath)
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true})
try {
  for(const [language,zone] of [['en-GB','Europe/London'],['en-US','America/Los_Angeles']]) {
    const context=await browser.newContext({timezoneId:zone,locale:language,viewport:{width:1280,height:960},reducedMotion:'reduce'})
    const page=await context.newPage(),errors=[]
    page.on('pageerror',error=>errors.push(error.message))
    page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
    const state=async()=>JSON.parse(await page.locator('#receipt').textContent())
    const open=()=>page.getByRole('button',{name:'Edit cut-offs',exact:true}).click()
    const input=label=>page.getByLabel(label+' (UTC)',{exact:true})
    const apply=()=>page.getByRole('button',{name:'Apply cut-offs',exact:true}).click()
    await page.goto(url+'?cutoffs&language='+language)
    await open()
    const original=await state()
    assert.equal(await input('Cargo cut-off').inputValue(),'2026-09-17T08:30:45')
    await input('Documentation cut-off').fill('2026-09-16T12:00')
    await input('VGM cut-off').fill('2026-09-17T16:00')
    await apply()
    assert.equal((await state()).routes[0].cargoCutoffAt,original.routes[0].cargoCutoffAt)
    assert.equal((await state()).routes[0].documentationCutoffAt,'2026-09-16T12:00:00Z')
    assert.equal((await state()).routes[0].vgmCutoffAt,'2026-09-17T16:00:00Z')
    await page.waitForFunction(()=>document.activeElement?.textContent==='Edit cut-offs')
    await open()
    await input('Cargo cut-off').fill('2026-09-18T10:00')
    await page.keyboard.press('Escape')
    assert.equal((await state()).routes[0].cargoCutoffAt,original.routes[0].cargoCutoffAt)
    await open()
    // Delete one native date/time segment, leaving a realistically incomplete
    // deadline. Validation must keep all three draft fields unapplied.
    await input('Cargo cut-off').fill('2026-09-18T10:00')
    await input('Cargo cut-off').press('Backspace')
    assert.equal(await input('Cargo cut-off').evaluate(el=>el.validity.badInput),true)
    await apply()
    assert.equal(await input('Cargo cut-off').getAttribute('aria-invalid'),'true')
    assert.equal((await state()).routes[0].cargoCutoffAt,original.routes[0].cargoCutoffAt)
    await input('Cargo cut-off').fill('2026-09-18T10:00')
    for(const width of [320,768,1280]) {
      await page.setViewportSize({width,height:960})
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),width)
      assert.equal(await page.getByRole('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth),true)
    }
    if(language==='en-GB')await page.screenshot({path:screenshot,fullPage:true})
    await page.evaluate(()=>{document.body.style.zoom='2'})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),1280)
    await page.evaluate(()=>{document.body.style.zoom='1'})
    await input('Cargo cut-off').focus();await page.keyboard.press('Tab')
    assert.notEqual(await page.evaluate(()=>document.activeElement?.tagName),'BODY')
    await apply()
    assert.equal((await state()).routes[0].cargoCutoffAt,'2026-09-18T10:00:00Z')
    await open()
    // Simulate an external route refresh in this isolated state fixture.
    await page.getByRole('button',{name:'Concurrent route change',exact:true,includeHidden:true}).evaluate(el=>el.click())
    await apply()
    assert.match(await page.getByRole('alert').textContent(),/routing step changed/)
    await page.getByRole('button',{name:'Cancel',exact:true}).click()
    await open();await input('Cargo cut-off').fill('');await apply()
    assert.equal((await state()).routes[0].cargoCutoffAt,'')
    assert.deepEqual((await state()).quoteSnapshot,original.quoteSnapshot)
    assert.equal((await state()).routes[0].plannedDepartureAt,original.routes[0].plannedDepartureAt)
    assert.equal((await state()).routes[0].routeData.actualArrivalAt,original.routes[0].routeData.actualArrivalAt)
    assert.equal('cargoCutoffAt' in (await state()).routes[0].routeData,false)
    await page.getByRole('button',{name:'Confirm Air mode',exact:true}).click()
    assert.equal((await state()).routes[0].documentationCutoffAt,'')
    assert.equal((await state()).routes[0].vgmCutoffAt,'')
    await open();assert.equal(await input('VGM cut-off').count(),0)
    await page.getByRole('button',{name:'Cancel',exact:true}).click()
    await page.getByRole('button',{name:'Read only',exact:true}).click()
    assert.equal(await page.getByRole('button',{name:'Edit cut-offs',exact:true}).count(),0)
    assert.deepEqual(errors,[])
    console.log(language+' / '+zone+': UTC, precise no-op, apply/cancel/clear, incomplete/stale refusal, mode reset, keyboard, read-only and responsive checks passed')
    await context.close()
  }
} finally {await browser.close()}
