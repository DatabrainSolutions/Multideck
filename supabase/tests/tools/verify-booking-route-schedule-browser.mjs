import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
const [url,packagePath,screenshot]=process.argv.slice(2)
if(!/^http:\/\/127\.0\.0\.1:\d+\/$/.test(url)||!packagePath||!screenshot)throw Error('Pass isolated fixture URL, Playwright package directory and screenshot path')
const {chromium}=createRequire(import.meta.url)(packagePath)
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true})
try {
  for(const [language,zone,motion] of [['en-GB','Europe/London','reduce'],['en-US','America/Los_Angeles','reduce'],['en-GB','Pacific/Kiritimati','reduce'],['en-US','America/New_York','no-preference']]) {
    const context=await browser.newContext({timezoneId:zone,locale:language,viewport:{width:1280,height:960},reducedMotion:motion})
    const page=await context.newPage(),errors=[]
    page.on('pageerror',error=>errors.push(error.message))
    const state=async()=>JSON.parse(await page.locator('#receipt').textContent())
    await page.goto(url+'?language='+language)
    // Native date/time inputs do not consistently expose textbox roles.
    const date=label=>page.getByLabel(label+' date (UTC)',{exact:true})
    const time=label=>page.getByLabel(label+' time (UTC)',{exact:true})
    await date('Planned departure').waitFor()
    const original=await state()
    assert.equal(await date('Planned departure').inputValue(),'2026-09-17')
    assert.equal(await time('Planned departure').inputValue(),'19:00:45')
    await date('Planned departure').fill('2026-09-20')
    assert.equal((await state()).routes[0].plannedDepartureAt,'2026-09-20T19:00:45.123456Z')
    await date('Planned pickup').fill('2026-09-18')
    await time('Planned pickup').fill('08:45:30')
    assert.equal((await state()).routes[0].plannedPickupAt,'2026-09-18T08:45:30Z')
    await date('Planned delivery').fill('2026-10-19')
    await time('Planned delivery').fill('11:30')
    assert.equal((await state()).routes[0].plannedDeliveryAt,'2026-10-19T11:30:00Z')
    await time('Planned delivery').focus();await page.keyboard.press('Tab')
    assert.notEqual(await page.evaluate(()=>document.activeElement?.tagName),'BODY')
    await date('Planned arrival').fill('')
    assert.equal((await state()).routes[0].plannedArrivalAt,'')
    assert.equal(await page.getByLabel('Planned arrival time (UTC)',{exact:true}).count(),0)
    assert.equal((await state()).routes[0].routeData.actualArrivalAt,'retained-history')
    assert.deepEqual((await state()).quoteSnapshot,original.quoteSnapshot)
    for(const width of [320,768,1280]) {
      await page.setViewportSize({width,height:960})
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),width)
    }
    await page.evaluate(()=>{document.body.style.zoom='2'})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),1280)
    await page.evaluate(()=>{document.body.style.zoom='1'})
    await page.getByRole('button',{name:'Read only',exact:true}).click()
    assert.equal(await page.locator('input').count(),0)
    assert.deepEqual(errors,[])
    if(zone==='Europe/London') await page.screenshot({path:screenshot,fullPage:true})
    await page.goto(url+'?language='+language+'&invalid=1')
    const clear=page.getByRole('button',{name:'Clear invalid timestamp: Planned departure',exact:true})
    await clear.waitFor()
    assert.equal((await state()).routes[0].plannedDepartureAt,'2026-09-18T08:45:00')
    assert.equal(await date('Planned departure').count(),0)
    await page.getByRole('button',{name:'Read only',exact:true}).click()
    assert.equal(await clear.count(),0)
    assert.equal((await state()).routes[0].plannedDepartureAt,'2026-09-18T08:45:00')
    await page.getByRole('button',{name:'Edit',exact:true}).click()
    await clear.focus();await page.keyboard.press('Enter')
    await date('Planned departure').waitFor()
    await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='Planned departure date (UTC)')
    assert.equal((await state()).routes[0].plannedDepartureAt,'')
    await date('Planned departure').fill('2026-09-21')
    assert.equal((await state()).routes[0].plannedDepartureAt,'2026-09-21')
    assert.deepEqual(errors,[])
    console.log(language+' / '+zone+' / '+motion+': UTC display, date/time edits, fractional preservation, clears, retained history, keyboard/read-only and reflow passed')
    await context.close()
  }
} finally {await browser.close()}
