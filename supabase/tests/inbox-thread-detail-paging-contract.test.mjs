test("conversation bodies are intent-driven and the UI exposes explicit older-message paging", () => {
  const warmEffect = workspace.slice(workspace.indexOf("// Warm only the first visible list page"), workspace.indexOf("const applySelection"))
  assert.match(warmEffect, /fetchThreadPage/)
  assert.doesNotMatch(warmEffect, /prefetchThreadDetail/)
  assert.match(page, /onPrefetch=\{\(\) => prefetchThreadDetail\(item\.id\)\}/)
  assert.match(page, /t\("Load older messages"\)/)
  assert.match(page, /fetchOlderThreadMessages\(targetThreadId, thread\.messages\.length\)/)
  assert.match(page, /role="alert"/)
})

