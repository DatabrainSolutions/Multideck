test("the database returns one exact, tenant-safe message page capped at 50", () => {
  assert.match(migration, /create or replace function public\.comm_inbox_thread_page\(/)
  assert.match(migration, /v_limit integer := greatest\(1, least\(coalesce\(p_limit, 25\), 50\)\)/)
  assert.match(migration, /'messageTotal', v_message_count/)
  assert.match(migration, /'hasOlderMessages'/)
  assert.match(migration, /limit v_limit\s+offset v_offset/)
  assert.match(migration, /where recipient\."CommRecipient_MessageID" in \(select id from message_ids\)/)
  assert.match(migration, /where attachment\."CommAttachment_MessageID" in \(select id from message_ids\)/)
  assert.match(migration, /where event\."CommDelivery_MessageID" in \(select id from message_ids\)/)
  assert.match(migration, /reply\."CommMessage_ReplyToMessageID" in/)
  assert.match(migration, /revoke all on function public\.comm_inbox_thread_page\(uuid,uuid,integer,integer\) from public, anon, authenticated/)
  assert.match(migration, /grant execute on function public\.comm_inbox_thread_page\(uuid,uuid,integer,integer\) to service_role/)
})

