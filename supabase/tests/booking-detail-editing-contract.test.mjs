import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import test from "node:test"

const root = new URL("../../", import.meta.url)
const read = (path) => readFile(new URL(path, root), "utf8")

const migration = await read("supabase/migrations/20260901100000_booking_detail_editing.sql")
const routingMigration = await read("supabase/migrations/20260902153715_booking_multi_leg_routes_and_cargo_dimensions.sql")
const bookingComponents = await read("multideck.client/src/components/multideck/booking-components.tsx")
const bookingApi = await read("multideck.client/src/lib/booking-workflow-api.ts")

test("booking detail edits have a dedicated persisted override boundary", () => {
  assert.match(migration, /add column if not exists "Job_EditableDetailsJSON" jsonb not null default '\{\}'::jsonb/)
  assert.match(migration, /create or replace function booking_api\.save_booking_detail_fields/)
  assert.match(migration, /booking_api\.has_permission\(caller_auth_user_id, 'Bookings\.Write'\)/)
  assert.match(migration, /office\."Company_ID" = app_user\."Company_ID"/)
  assert.match(migration, /jsonb_object_agg\(entry\.key, entry\.value\)/)
  assert.match(migration, /create or replace function booking_api\.workspace_extended/)
  assert.match(migration, /App_UserJobStars/)
  assert.match(migration, /perform booking_api\.save_booking_detail_fields\(caller_auth_user_id, requested_job_id, payload\)/)
  for (const key of ["progress", "lastUpdated", "sourceId", "documentsStatus", "workflowStatus", "routeSummary", "customFields"]) {
    assert.match(migration, new RegExp(`'${key}'`, "u"))
  }
  assert.match(migration, /entry\.key like 'customField:%'/u)
  assert.match(migration, /length\(entry\.key\) <= 180/u)
})

