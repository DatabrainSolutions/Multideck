test("booking routing steps and item dimensions persist through the tenant-safe booking boundary", () => {
  assert.match(bookingComponents, /Add routing step/u)
  assert.match(bookingComponents, /workspace\.routes\.map\(\(leg, index\)/u)
  assert.match(bookingComponents, /routes: workspace\.routes\.map/u)
  assert.match(bookingComponents, /modeKey === "ocean" \|\| modeKey === "sea"/u)
  for (const field of ["Length", "Width", "Height", "Dimension unit"]) {
    assert.match(bookingComponents, new RegExp(`label="${field}"`, "u"))
  }
  assert.match(routingMigration, /create or replace function booking_api\.save_booking_route_legs/u)
  assert.match(routingMigration, /jsonb_array_length\(payload->'routes'\) > 30/u)
  assert.match(routingMigration, /office\."Company_ID" = app_user\."Company_ID"/u)
  assert.match(routingMigration, /That routing step does not belong to this booking/u)
  assert.match(routingMigration, /create or replace function booking_api\.save_booking_cargo_measurements/u)
  assert.match(routingMigration, /"JobCargo_Length" = nullif\(line->>'length', ''\)::numeric/u)
  assert.match(routingMigration, /jsonb_array_elements\(coalesce\(result->'cargo', '\[\]'::jsonb\)\) as item\(value\)/u)
  assert.match(routingMigration, /item\.value \|\| jsonb_strip_nulls/u)
  assert.match(routingMigration, /perform booking_api\.save_booking_route_legs/u)
  assert.match(routingMigration, /revoke all on function booking_api\.save_booking_route_legs/u)
  assert.doesNotMatch(routingMigration, /delete from public\."Job_Routing"/u)
  assert.match(routingMigration, /Ordered routing-step and item-dimension editing is not supported in Dexter/u)
  assert.match(routingMigration, /Ordered route-leg and cargo-dimension watches are not supported/u)
  assert.match(bookingComponents, /BookingCargoWiseField label="ETD" value=\{estimatedDeparture\} inputType="date"/u)
  assert.match(bookingComponents, /BookingCargoWiseField label="ETA" value=\{estimatedArrival\} inputType="date"/u)
  assert.match(bookingComponents, /const estimatedDeparture = firstRoute\?\.plannedDepartureAt \|\| record\.booking\.departureDate/u)
  assert.match(bookingComponents, /const estimatedArrival = lastRoute\?\.plannedArrivalAt \|\| record\.booking\.arrivalDate \|\| record\.booking\.eta/u)
  assert.match(bookingComponents, /const lastRoute = workspace\.routes\.at\(-1\) \?\? route/u)
  assert.match(routingMigration, /apply_accepted_quote_schedule_to_new_route/u)
  assert.match(routingMigration, /JobRoute_PlannedDepartureAt/u)
  assert.match(routingMigration, /JobRoute_PlannedArrivalAt/u)
})

